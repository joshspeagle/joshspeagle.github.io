# ---------------------------------------------------------------------------
# Structured data (schema.org JSON-LD) — a Person on every indexed page, plus the
# publication list on Publications. Built from the same data as the visible page,
# so it cannot drift from what a reader sees.
# ---------------------------------------------------------------------------

def _json_ld(obj):
    """Serialize one JSON-LD block. `<` is escaped so the payload can never close
    the script element."""
    body = json.dumps(obj, ensure_ascii=False, separators=(",", ":")).replace("<", "\\u003c")
    return f'  <script type="application/ld+json">{body}</script>'


def person_schema(data):
    """schema.org Person for the site owner, from content.json."""
    site = data.get("site", {}) or {}
    links = (data.get("sections", {}).get("publications", {}) or {}).get("links", {}) or {}
    contact = (data.get("sections", {}).get("about", {}) or {}).get("contactInfo", {}) or {}
    same_as = [links.get("orcid"), links.get("scholar")]
    github_user = load_data_file("software").get("githubUser")
    if github_user:
        same_as.append(f"https://github.com/{github_user}")
    person = {
        "@type": "Person",
        "name": SITE_NAME,
        "url": f"{SITE_URL}/",
        "image": f"{SITE_URL}/{OG_IMAGE}",
        "sameAs": [u for u in same_as if u],
    }
    home = (data.get("pages", {}) or {}).get("home", {}) or {}
    if home.get("nameZh"):
        # nameZh carries display spacing ("沈 佳 士"); structured data wants the name.
        person["alternateName"] = "".join(home["nameZh"].split())
    if site.get("jobTitle"):
        person["jobTitle"] = site["jobTitle"]
    if contact.get("email"):
        person["email"] = f'mailto:{contact["email"]}'
    aff = site.get("affiliation") or {}
    if aff.get("name"):
        person["affiliation"] = {k: v for k, v in
                                 (("@type", "Organization"), ("name", aff.get("name")),
                                  ("url", aff.get("url"))) if v}
    return person


def render_structured_data(key, page, data):
    """JSON-LD for one page: the Person everywhere, plus a CollectionPage describing
    Publications. 404 (noindex) gets none.

    The 136 papers are deliberately NOT inlined as ScholarlyArticle nodes: measured,
    that adds 60 KB (+11 KB gzipped, +26%) to publications.html, no search engine
    surfaces ScholarlyArticle rich results, and the page already links the complete
    machine-readable record as BibTeX.
    """
    if not page.get("canonical"):
        return ""
    blocks = [{"@context": "https://schema.org", **person_schema(data)}]
    if key == "publications":
        papers = [p for p in load_data_file("publications").get("publications", [])
                  if p.get("year")]
        blocks.append({
            "@context": "https://schema.org",
            "@type": "CollectionPage",
            "url": f'{SITE_URL}{page["canonical"]}',
            "name": _page_title(key, page, data),
            "about": {"@type": "Person", "name": SITE_NAME, "url": f"{SITE_URL}/"},
            "mainEntity": {"@type": "ItemList", "numberOfItems": len(papers)},
            "encoding": {"@type": "MediaObject",
                         "encodingFormat": "application/x-bibtex",
                         "contentUrl": f"{SITE_URL}/{BIBTEX_PATH}"},
        })
    return "\n".join(_json_ld(b) for b in blocks)


def _footer_elsewhere(data):
    """The "Elsewhere" footer column: the author profiles declared in
    sections.publications.links, plus the GitHub account software_data.json fetches."""
    declared = ((data.get("sections", {}).get("publications", {}) or {}).get("links") or {})
    labels = [("ads", "ADS"), ("scholar", "Google Scholar"), ("orcid", "ORCID")]
    links = [(label, declared[key]) for key, label in labels if declared.get(key)]
    user = load_data_file("software").get("githubUser")
    if user:
        links.insert(2, ("GitHub", f"https://github.com/{user}"))
    return "".join(
        f'<li><a href="{url_attr(url)}" target="_blank" rel="noopener">{esc(name)}</a></li>'
        for name, url in links)


def render_footer(page, data, root):
    """Site footer: the brand lockup, one link column per NAV group plus "Elsewhere",
    and the copyright line. Both dates come from the data files (see data_date): the
    stamp from this page's own sources, the © year from the newest of all of them."""
    note = page.get("footer", DEFAULT_FOOTER_NOTE)
    stamp = source_date(page)
    updated = f' · Updated {stamp.strftime("%B %Y")}' if stamp else ""
    year = site_updated()
    copyright_ = f"© {year.year} " if year else ""
    site = data.get("site", {}) or {}

    columns = []
    for entry in NAV:                       # the nav registry IS the footer sitemap
        if not entry.get("items"):
            continue
        rows = ""
        for item in entry["items"]:
            href, label, _cur, ext = _nav_link(item, None, root)
            rows += f'<li><a href="{href}"{ext}>{label}</a></li>'
        columns.append((entry["label"], rows))
    columns.append(("Elsewhere", _footer_elsewhere(data)))
    cols_html = "".join(
        f'        <div><h2>{label}</h2><ul>{rows}</ul></div>\n'
        for label, rows in columns if rows)

    blurb = esc(site.get("jobTitle", ""))
    if site.get("affiliation", {}).get("name"):
        blurb = f'{blurb} · {esc(site["affiliation"]["name"])}' if blurb else esc(site["affiliation"]["name"])
    return ('  <footer class="site-footer">\n'
            '    <div class="container">\n'
            '      <div class="foot">\n'
            '        <div>\n'
            f'          <a class="brand" href="{root}index.html">'
            f'<svg class="mark" aria-hidden="true" focusable="false"><use href="#mark-s"/></svg>'
            f'{SITE_NAME}</a>\n'
            f'          <p class="foot-blurb">{blurb}</p>\n'
            '        </div>\n'
            f'{cols_html}'
            '      </div>\n'
            '      <div class="foot-copy">\n'
            f'        <span>{copyright_}{SITE_NAME} · <span class="zh">沈佳士</span></span>\n'
            f'        <span>{note}{updated}</span>\n'
            '      </div>\n'
            '    </div>\n'
            '  </footer>')


