    yp = lambda v: (1 - v / scale) * 100
    pts = [(xp(i), yp(cpy[y])) for i, y in enumerate(years)]

    line = " ".join(f"{'M' if i == 0 else 'L'}{_n(x)},{_n(y)}" for i, (x, y) in enumerate(pts))
