def meta_description_clamp(text):
    """Collapse whitespace, strip markup and clamp to 160 characters at a word
    boundary (a hand-written pages.<key>.description goes through this unchanged
    unless it is too long)."""
    body = re.sub(r"\s+", " ", strip_tags(text)).strip()
    if len(body) <= 160:
        return body
    warn(f"meta description is {len(body)} characters; truncated to 160: {body[:60]}…")
    return body[:159].rsplit(" ", 1)[0] + "…"


def meta_description(text):
    """Build a <=160-character meta/OG description from a page tagline: strip markup,
    then append the longest name suffix that still fits."""
    body = re.sub(r"\s+", " ", strip_tags(text)).strip().rstrip(".")
    for suffix in _DESC_SUFFIXES:
        if len(body) + len(suffix) <= 160:
            return body + suffix
    return meta_description_clamp(body)


def _page_description(key, page, data):
    """Per-page description: pages.<key>.description in content.json wins, then a
    registry override, else derived from pages.<key>.tagline (publications gets the
    live pipeline metrics instead, so it can never go stale)."""
    declared = page_meta(data, key).get("description")
    if declared:
        return meta_description_clamp(declared)
    if page.get("description"):
        return page["description"]
    if key == "publications":
        m = _pub_metrics()
        bits = [f'{m.get("totalPapers", 0):,} papers']
        if m.get("totalCitations"):
            bits.append(f'{m["totalCitations"]:,} citations')
        if m.get("hIndex"):
            bits.append(f'h-index {m["hIndex"]}')
        return meta_description("Peer-reviewed publications and preprints — " + ", ".join(bits))
    return meta_description(page_meta(data, key).get("tagline", ""))


def _page_title(key, page, data):
    if page.get("title"):
        return page["title"]
    return f'{esc_text(page_meta(data, key).get("title", key.title()))} · {SITE_NAME}'


