def build_page(key, data):
    """Render one complete page: generate its content, then wrap it in the shell."""
    if key == "index":
        content = [(sec_id, cls, gen(data)) for sec_id, cls, gen in _HOME_SECTIONS]
    elif key in _CONTENT_GENERATORS:
        content = _CONTENT_GENERATORS[key](data)
    else:
        content = ""            # 404: the shell supplies the whole body
    return render_shell(key, data, content)


def main():
    """Render every registered page (plus sitemap.xml) from the data files."""
    print(f"Loading content from {CONTENT_JSON}...")
    if not CONTENT_JSON.exists():
        print(f"ERROR: {CONTENT_JSON} not found", file=sys.stderr)
        sys.exit(1)

    data = json.loads(CONTENT_JSON.read_text(encoding="utf-8"))

    failures = 0
    for key, page in PAGES.items():
        path = PROJECT_ROOT / page["file"]
        print(f"  Rendering {page['file']}...")
        try:
            html = build_page(key, data)
        except (BuildError, KeyError, OSError, TypeError, ValueError) as err:
            # One bad data file must not block the other pages.
            print(f"    ERROR: {page['file']} not rendered: {type(err).__name__}: {err}",
                  file=sys.stderr)
            failures += 1
            continue
        if not path.exists() or path.read_text(encoding="utf-8") != html:
            path.write_text(html, encoding="utf-8")
            print(f"    -> Updated {page['file']}")
        else:
            print(f"    -> No changes needed for {page['file']}")

    write_sitemap()
    write_feed(data)

    if failures:
        print(f"Done with {failures} page(s) failing. See the errors above.", file=sys.stderr)
        sys.exit(1)
    print("Done! Every page has been rendered from assets/data/.")


if __name__ == "__main__":
    main()
