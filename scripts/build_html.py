def write_sitemap():
    """Write sitemap.xml from the registry: one <url> per indexed page, with a
    lastmod derived from that page's data sources."""
    rows = []
    for key, page in PAGES.items():
        if not page.get("sitemap") or not page.get("canonical"):
            continue
        stamp = source_date(page)
        lastmod = f'        <lastmod>{stamp.isoformat()}</lastmod>\n' if stamp else ""
        rows.append('    <url>\n'
                    f'        <loc>{SITE_URL}{page["canonical"]}</loc>\n'
                    f'{lastmod}'
                    f'        <priority>{page["sitemap"]}</priority>\n'
                    '    </url>')
    xml = ('<?xml version="1.0" encoding="UTF-8"?>\n'
           '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
           + "\n".join(rows) + "\n</urlset>\n")
    old = SITEMAP_XML.read_text(encoding="utf-8") if SITEMAP_XML.exists() else None
    if old != xml:
        SITEMAP_XML.write_text(xml, encoding="utf-8")
        print("  -> Updated sitemap.xml")
    return xml

_RFC822_MONTHS = ["Jan", "Feb", "Mar", "Apr", "May", "Jun",
                  "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"]


def _news_date(item):
    """(date, RFC-822 string) for a news item. Items carry month precision
    ("Aug 2026"), so they are dated to the 1st of that month."""
    year = int(item.get("year") or 0) or 1970
    month = term_month(item.get("date", "")) or 1
    return date(year, month, 1), _rfc822(date(year, month, 1))


def _rfc822(d):
    """RFC-822 date for RSS (no locale dependency, no time of day)."""
    return f"{d.day:02d} {_RFC822_MONTHS[d.month - 1]} {d.year} 00:00:00 +0000"


def write_feed(data):
    """Write feed.xml: an RSS 2.0 feed of sections.news.items.

    Item guids are stable, non-permalink tags built from the date + title slug, so a
    reader never re-shows an item because an unrelated item was added above it.
    """
    news = (data.get("sections", {}).get("news", {}) or {})
    items = news.get("items", []) or []
    types = news.get("types", {}) or {}
    news_url = f'{SITE_URL}{PAGES["news"]["canonical"]}'
    rows, seen = [], set()
    for item in sorted(items, key=lambda n: _news_date(n)[0], reverse=True):
        stamp, rfc822 = _news_date(item)
        title = strip_tags(item.get("title", ""))
        guid = f'tag:joshspeagle.com,{stamp.isoformat()}:news/{slug(title)[:60]}'
        while guid in seen:                       # two items, one month, one slug
            guid += "-b"
        seen.add(guid)
        label = (types.get(item.get("type")) or {}).get("label", "")
        body = strip_tags(item.get("blurb", ""))
        rows.append('    <item>\n'
                    f'      <title>{esc_text(title)}</title>\n'
                    f'      <link>{esc_text(item.get("link") or news_url)}</link>\n'
                    f'      <guid isPermaLink="false">{esc_text(guid)}</guid>\n'
                    f'      <pubDate>{rfc822}</pubDate>\n'
                    + (f'      <category>{esc_text(label)}</category>\n' if label else "")
                    + f'      <description>{esc_text(body)}</description>\n'
                    '    </item>')
    built = data_date("content")
    xml = ('<?xml version="1.0" encoding="UTF-8"?>\n'
           '<rss version="2.0" xmlns:atom="http://www.w3.org/2005/Atom">\n'
           '  <channel>\n'
           f'    <title>{SITE_NAME} · News</title>\n'
           f'    <link>{news_url}</link>\n'
           f'    <description>News and press from {SITE_NAME}, astrostatistics at the '
           'University of Toronto.</description>\n'
           '    <language>en-us</language>\n'
           f'    <atom:link href="{SITE_URL}/{FEED_FILE}" rel="self" type="application/rss+xml"/>\n'
           + (f'    <lastBuildDate>{_rfc822(built)}</lastBuildDate>\n' if built else "")
           + "\n".join(rows) + '\n  </channel>\n</rss>\n')
    old = FEED_XML.read_text(encoding="utf-8") if FEED_XML.exists() else None
    if old != xml:
        FEED_XML.write_text(xml, encoding="utf-8")
        print(f"  -> Updated {FEED_FILE}")
    return xml


