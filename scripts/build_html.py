# researchArea label -> (key, badge label with escaped &)
_PUB_CAT_MAP = {
    "Statistical Learning & AI": ("sla", "Statistical Learning &amp; AI"),
    "Interpretability & Insight": ("ii", "Interpretability &amp; Insight"),
    "Inference & Computation": ("ic", "Inference &amp; Computation"),
    "Discovery & Understanding": ("du", "Discovery &amp; Understanding"),
}

# Stable order for emitting category badges (matches the 4 areas)
_PUB_CAT_ORDER = [
    "Statistical Learning & AI",
    "Interpretability & Insight",
    "Inference & Computation",
    "Discovery & Understanding",
]


# Category key -> badge label (reverse of _PUB_CAT_MAP, in _PUB_CAT_ORDER order)
_PUB_CAT_LABEL = {key: label for key, label in _PUB_CAT_MAP.values()}


def _cat_probs(pub):
    """(category name, probability) for the four areas, in badge order."""
    probs = pub.get("categoryProbabilities", {}) or {}
    out = []
    for cat in _PUB_CAT_ORDER:
        try:
            out.append((cat, float(probs.get(cat, 0))))
        except (TypeError, ValueError):
            out.append((cat, 0.0))
    return out


def _pub_badge_keys(pub):
    """Category keys BADGED on a card: every area with probability >= 0.20, so a
    paper can advertise that it spans more than one area."""
    keys = [_PUB_CAT_MAP[cat][0] for cat, prob in _cat_probs(pub) if prob >= 0.20]
    return keys or [_pub_cat_key(pub)]


def _pub_cat_key(pub):
    """The single area a paper is FILED under: argmax(categoryProbabilities), which
    the pipeline also stores as researchArea. Card accent, data-cat filter key and
    chip count all read this one value, so the stripe you see is the chip you clicked
    and the chips partition the corpus."""
    cat, prob = max(_cat_probs(pub), key=lambda cp: cp[1])
    if prob > 0:
        return _PUB_CAT_MAP[cat][0]
    return _PUB_CAT_MAP.get(pub.get("researchArea", ""), ("du", ""))[0]


# Group bylines that must render verbatim rather than as "F. Last".
_COLLAB_RE = re.compile(r"\b(collaboration|consortium|team|survey)\b", re.I)


def _format_author(author):
    """Format one author for display: 'Last, First M.' and 'First M. Last' both become
    'F. Last'; collaboration/consortium bylines and all-caps acronyms render verbatim.
    Speagle is wrapped in <strong>. Returns the escaped HTML string."""
    is_speagle = "speagle" in author.lower()
    name = author.strip()
    if _COLLAB_RE.search(name) or ("," not in name and name.isupper() and len(name) > 1):
        # Collaboration/consortium bylines and acronyms are not personal names.
        return f"<strong>{esc(name)}</strong>" if is_speagle else esc(name)
    if "," in author:
        last, _, first = author.partition(",")
        last = last.strip()
        first = first.strip()
    else:
        parts = author.strip().split()
        if len(parts) >= 2:
            last = parts[-1]
            first = " ".join(parts[:-1])
        else:
            last = author.strip()
            first = ""
    initial = ""
    fp = first.strip()
    if fp:
        # Use the first alphabetic character of the first name as the initial
        for ch in fp:
            if ch.isalpha():
                initial = ch.upper() + ". "
                break
    display = esc(f"{initial}{last}".strip())
    if is_speagle:
        display = f"<strong>{display}</strong>"
    return display


def _format_authors_html(authors):
    """Show first 3 authors as 'F. Last', append ' et al.' if more than 3."""
    if not authors:
        return ""
    shown = [_format_author(a) for a in authors[:3]]
    html = ", ".join(shown)
    if len(authors) > 3:
        html += " et al."
    return html


def _truncate(s, n=320):
    """Clean + escape + truncate prose at a word boundary for the featured abstract."""
    s = clean_text(s)
    if len(s) <= n:
        return esc(s)
    return esc(s[:n].rsplit(" ", 1)[0]) + "…"


