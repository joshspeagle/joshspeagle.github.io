# ---------------------------------------------------------------------------
# Data freshness (footer "Updated <Month Year>" + sitemap lastmod)
#
# Every date on the site is READ FROM THE DATA, never from the clock or from git:
# each data file declares when it was last updated, so rebuilding the site from the
# repository alone is byte-identical no matter which day it runs (the CI staleness
# gate diffs the committed build against a rebuild). The publication and software
# caches own their own timestamps (their fetch scripts write them); content.json
# carries site.lastUpdated, bumped by whoever edits it.
# ---------------------------------------------------------------------------

# data key -> dotted paths to try, in order, for that file's freshness date
_DATE_FIELDS = {
    "content": ("site.lastUpdated",),
    "publications": ("metrics.lastUpdated", "lastUpdated"),
    "software": ("lastUpdated", "lastFetched"),
}

_JSON_CACHE = {}
_DATE_CACHE = {}


def load_data_file(key):
    """Parsed contents of one registered data file ({} when it cannot be read)."""
    if key not in _JSON_CACHE:
        try:
            _JSON_CACHE[key] = json.loads(DATA_FILES[key].read_text(encoding="utf-8"))
        except (OSError, ValueError) as err:
            warn(f"cannot read {DATA_FILES[key].name}: {err}")
            _JSON_CACHE[key] = {}
    return _JSON_CACHE[key]


def _dig(blob, path):
    """Look up a dotted path in nested dicts; None when any step is missing."""
    for part in path.split("."):
        if not isinstance(blob, dict):
            return None
        blob = blob.get(part)
    return blob


def data_date(key):
    """The update date a data file declares for itself, or None if it declares none."""
    if key not in _DATE_CACHE:
        found = None
        for field in _DATE_FIELDS[key]:
            try:
                found = date.fromisoformat(str(_dig(load_data_file(key), field))[:10])
                break
            except (TypeError, ValueError):
                continue
        if found is None:
            warn(f"{DATA_FILES[key].name} declares no update date "
                 f"({' / '.join(_DATE_FIELDS[key])}); pages built from it carry no "
                 f"'Updated' stamp")
        _DATE_CACHE[key] = found
    return _DATE_CACHE[key]


def source_date(page):
    """Newest declared update date across a page's data sources (None if none)."""
    dates = [d for d in (data_date(k) for k in page.get("sources", ["content"])) if d]
    return max(dates) if dates else None


def site_updated():
    """Newest declared update date across every data file (drives the © year)."""
    dates = [d for d in (data_date(k) for k in DATA_FILES) if d]
    return max(dates) if dates else None


